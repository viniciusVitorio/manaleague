const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {console};
vm.createContext(context);
vm.runInContext(fs.readFileSync('public/js/deck-simulator.js', 'utf8'), context);
const Simulator = context.DeckSimulator;
const cards = [{name:'Land',quantity:24,land:true}, {name:'Spell',quantity:36,land:false}];
const sim = new Simulator(cards, () => 0.5);
assert.equal(sim.hand.length,7);
assert.equal(sim.library.length,53);
assert.throws(() => sim.draw());
sim.mulligan(); sim.mulligan();
assert.equal(sim.hand.length,7);
assert.equal(sim.bottomCount,2);
assert.throws(() => sim.keep([0]));
assert.throws(() => sim.keep([0,0]));
sim.keep([0,2]);
assert.equal(sim.hand.length,5);
assert.equal(sim.library.length,55);
assert.equal(sim.draw().name.length > 0,true);
assert.equal(sim.hand.length,6);
assert.throws(() => sim.mulligan());
for(let i=0;i<60;i++) sim.draw();
assert.equal(sim.library.length,0);
assert.equal(sim.hand.length,60);
assert.equal(sim.draw(),null);
sim.reset(); assert.equal(sim.hand.length,7); assert.equal(sim.bottomCount,0);
for(let i=0;i<7;i++) sim.mulligan();
assert.throws(() => sim.mulligan());
sim.keep([0,1,2,3,4,5,6]); assert.equal(sim.hand.length,0);
const empty = new Simulator([]); assert.equal(empty.hand.length,0); empty.keep([]); assert.equal(empty.draw(),null);
const stats = new Simulator([{name:'Land',quantity:60,land:true}], () => 0.25).statistics(100);
assert.equal(stats.samples,100); assert.equal(stats.averageLands,7); assert.equal(stats.distribution[7],100);
const short = new Simulator([{name:'Spell',quantity:3,land:false}]); assert.equal(short.hand.length,3);
assert.equal(short.statistics(100).averageLands,0);
const free = new Simulator(cards, () => 0.5, true); free.mulligan(); assert.equal(free.bottomCount,0); free.mulligan(); assert.equal(free.bottomCount,1);
console.log('PASS: London mulligan, free mulligan, exact bottom selection, draws, reset, exhaustion, empty/short decks and statistics');
